#!/usr/bin/env python3
"""Render a keyless GCS config, or an explicitly local POSIX fixture config.

No network, credentials, SDK, or filesystem mutation. Redirect stdout only to a
reviewed, root-owned config outside Git. Restore must use the same pgBackRest.
"""
import argparse
import json
import re
from pathlib import PurePosixPath

PGDATA = "/var/lib/postgresql/18/docker"


def checked_path(value):
    p = PurePosixPath(value)
    if not value.startswith("/") or ".." in p.parts or "//" in value or "\n" in value:
        raise ValueError("invalid absolute path")
    return str(p)


def render(*, bucket=None, prefix="pgbackrest/longbeach/", posix_path=None):
    if (bucket is None) == (posix_path is None):
        raise ValueError("choose GCS or local POSIX fixture")
    if bucket is not None:
        if not re.fullmatch(r"[a-z0-9][a-z0-9._-]{1,220}[a-z0-9]", bucket):
            raise ValueError("invalid bucket name")
        if not re.fullmatch(r"[a-zA-Z0-9_-]+(?:/[a-zA-Z0-9_-]+)*/?", prefix):
            raise ValueError("invalid dedicated repository prefix")
        repo = ("repo1-type=gcs\n" + "repo1-gcs-bucket=" + bucket + "\n"
                "repo1-gcs-key-type=auto\nrepo1-path=/" + prefix.rstrip("/") + "\n")
    else:
        repo = "repo1-type=posix\nrepo1-path=" + checked_path(posix_path) + "\n"
    return """# Generated by render-config.py. No service-account key or DB password.
[global]
""" + repo + """repo1-retention-full-type=time
repo1-retention-full=8
# Do not set retention-archive: retain continuous WAL from the oldest full.
archive-async=n
archive-check=y
archive-timeout=120
compress-type=zst
compress-level=3
process-max=1
start-fast=n
spool-path=/var/spool/pgbackrest
lock-path=/var/run/pgbackrest
log-path=/var/log/pgbackrest
log-level-console=info
log-level-file=info
log-subprocess=n
io-timeout=60
db-timeout=1800
protocol-timeout=1830

[longbeach]
pg1-path=/var/lib/postgresql/18/docker
pg1-port=5432
pg1-socket-path=/var/run/postgresql
pg1-user=postgres
pg1-database=postgres
"""


def main():
    p = argparse.ArgumentParser(description=__doc__)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--manifest", help="read only backup.bucket/prefix from bootstrap JSON")
    mode.add_argument("--bucket")
    mode.add_argument("--posix-path", help="LOCAL SYNTHETIC TEST ONLY")
    p.add_argument("--prefix", default="pgbackrest/longbeach/")
    a = p.parse_args()
    if a.manifest:
        with open(a.manifest, encoding="utf-8") as f:
            backup = json.load(f)["backup"]
        print(render(bucket=backup["bucket"], prefix=backup["prefix"]), end="")
    else:
        print(render(bucket=a.bucket, prefix=a.prefix, posix_path=a.posix_path), end="")


if __name__ == "__main__":
    main()
